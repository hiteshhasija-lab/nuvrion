const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');

test('Windows setup wizard supports clean install, upgrade, ISO folders, and five-second state polling',()=>{
  const wizard=fs.readFileSync('deploy/workstation-agent/install-gui.ps1','utf8'),install=fs.readFileSync('deploy/workstation-agent/install.ps1','utf8'),upgrade=fs.readFileSync('deploy/workstation-agent/upgrade-lab.ps1','utf8'),launcher=fs.readFileSync('apps/workstation-agent/src/setup-launcher.cjs','utf8');
  const uiMedia=fs.readFileSync('deploy/workstation-agent/workstation-ui-media.ps1','utf8');
  const desktopCompanion=fs.readFileSync('deploy/workstation-agent/workstation-desktop-companion.ps1','utf8');
  assert.match(wizard,/Nuvrion Workstation Agent Setup/);
  assert.match(wizard,/upgrade-lab\.ps1/);
  assert.match(wizard,/Authorized ISO folders/);
  assert.match(wizard,/isoSearchRoots/);
  assert.match(wizard,/FolderBrowserDialog/);
  assert.match(wizard,/Select a folder containing ISO images/);
  assert.match(wizard,/saved\.isoSearchRoots/);
  assert.match(wizard,/allowHostDriveBrowsing/);
  assert.match(wizard,/metadataPollIntervalMs -NotePropertyValue 60000 -Force/);
  assert.match(upgrade,/metadataPollIntervalMs -NotePropertyValue 60000 -Force/);
  assert.match(install,/"staticMetadataCacheMs":300000/);
  assert.match(install,/"guestMetadataCacheMs":300000/);
  assert.match(install,/"storageMetadataCacheMs":300000/);
  assert.match(upgrade,/staticMetadataCacheMs -NotePropertyValue 300000 -Force/);
  assert.match(upgrade,/guestMetadataCacheMs -NotePropertyValue 300000 -Force/);
  assert.match(upgrade,/storageMetadataCacheMs -NotePropertyValue 300000 -Force/);
  assert.match(wizard,/commandPollIntervalMs -NotePropertyValue 500 -Force/);
  assert.match(upgrade,/commandPollIntervalMs -NotePropertyValue 500 -Force/);
  assert.match(wizard,/Browse\.\.\./);
  assert.doesNotMatch(wizard,/Browse…/);
  assert.match(install,/\[string\[\]\]\$IsoSearchRoots/);
  assert.match(install,/"allowHostDriveBrowsing":true/);
  assert.match(install,/"pollIntervalMs":5000/);
  assert.match(install,/"commandPollIntervalMs":500/);
  assert.match(install,/workstation-ui-media\.ps1/);
  assert.match(upgrade,/workstation-ui-media\.ps1/);
  assert.match(install,/workstation-desktop-companion\.ps1/);
  assert.match(upgrade,/workstation-desktop-companion\.ps1/);
  assert.match(install,/NuvrionWorkstationDesktopCompanion/);
  assert.match(upgrade,/NuvrionWorkstationDesktopCompanion/);
  assert.match(install,/desktopMediaQueuePath/);
  assert.match(upgrade,/desktopMediaQueuePath/);
  assert.match(desktopCompanion,/NotifyIcon/);
  assert.match(desktopCompanion,/desktop-media/);
  assert.match(desktopCompanion,/\.request\.json/);
  assert.match(desktopCompanion,/\.response\.json/);
  assert.match(desktopCompanion,/workstation-ui-media\.ps1/);
  assert.match(uiMedia,/UIAutomationClient/);
  assert.match(uiMedia,/Virtual Machine Settings/);
  assert.match(uiMedia,/TreeScope\]::Children/);
  assert.match(uiMedia,/Set-ControlValue \$isoField \$IsoPath/);
  assert.match(uiMedia,/durationMs=\$clock\.ElapsedMilliseconds/);
  assert.match(uiMedia,/Wait-WindowClosed/);
  assert.match(uiMedia,/settingsClosed=\$settingsClosed/);
  assert.match(uiMedia,/Find-VmWindow/);
  assert.match(uiMedia,/Find-TopLevelWindows/);
  assert.match(uiMedia,/NativeWindowHandle/);
  assert.doesNotMatch(uiMedia,/Where-Object\{\$_\.MainWindowHandle -ne 0\}/);
  assert.match(uiMedia,/Select-VmTab/);
  assert.match(uiMedia,/\$pattern\.Current\.IsSelected/);
  assert.match(uiMedia,/Open-VmSettings/);
  assert.match(uiMedia,/Edit virtual machine settings/);
  assert.match(uiMedia,/Find-ProcessNamed/);
  assert.match(uiMedia,/Settings…/);
  assert.match(uiMedia,/AttachThreadInput/);
  assert.match(uiMedia,/GetForegroundWindow/);
  assert.match(uiMedia,/SendCtrlD/);
  assert.match(uiMedia,/keybd_event/);
  assert.match(uiMedia,/mouse_event/);
  assert.match(uiMedia,/BoundingRectangle/);
  assert.match(uiMedia,/NuvrionDesktopWindow\]::Click/);
  assert.match(uiMedia,/Click-Control/);
  assert.match(uiMedia,/Get-VmwareDiagnostics/);
  assert.match(uiMedia,/MainWindowHandle/);
  assert.match(uiMedia,/WScript\.Shell/);
  assert.match(uiMedia,/AppActivate\(\$ProcessId\)/);
  assert.match(uiMedia,/\$shell\.SendKeys\('\^d'\)/);
  assert.match(uiMedia,/Wait-VmwareWindow/);
  assert.match(uiMedia,/Wait-VmwareWindowClosed/);
  assert.match(uiMedia,/assist-mount/);
  assert.match(uiMedia,/Set-Clipboard -Value \$IsoPath/);
  assert.match(uiMedia,/status='prepared'/);
  assert.match(wizard,/Enable-ScheduledTask -TaskName 'NuvrionWorkstationAgent'/);
  assert.match(upgrade,/Enable-ScheduledTask -TaskName \$TaskName/);
  assert.match(upgrade,/Expected exactly one Workstation Agent process after upgrade/);
  assert.match(upgrade,/Copy-Item -Force -LiteralPath \$backup -Destination \$target/);
  assert.match(install,/Expected exactly one Workstation Agent process after setup/);
  assert.match(wizard,/The setup package is incomplete/);
  assert.doesNotMatch(upgrade,/if\(\$taskWasEnabled\)\{Enable-ScheduledTask/);
  assert.match(launcher,/install-gui\.ps1/);
  assert.match(launcher,/powershell\.exe/);
  assert.match(launcher,/'-Sta'/);
  assert.match(launcher,/Nuvrion-Setup\.log/);
  assert.match(launcher,/child\.once\('close'/);
  assert.match(launcher,/showError/);
  assert.doesNotMatch(launcher,/const child=spawn\([^\n]+detached:true/);
  assert.doesNotMatch(launcher,/spawnSync/);
});
